#!/usr/bin/env python3
"""Rebuild the embedded NVN procedures with the aarch64-unknown-linux-gnu Rust target."""
import argparse
import subprocess
from pathlib import Path

from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parents[1]
GUEST = ROOT / "crates/nvn/guest"
TARGET = "aarch64-unknown-linux-gnu"


def compile_elf():
    rustc_version = subprocess.check_output(["rustc", "-vV"], text=True)
    host = next(line.removeprefix("host: ") for line in rustc_version.splitlines() if line.startswith("host: "))
    sysroot = subprocess.check_output(["rustc", "--print", "sysroot"], text=True).strip()
    linker = Path(sysroot) / "lib/rustlib" / host / "bin/rust-lld"
    target_dir = ROOT / "target/nvn-guest"
    subprocess.run([
        "cargo", "rustc", "--manifest-path", GUEST / "Cargo.toml", "--locked", "--release",
        "--target", TARGET, "--target-dir", target_dir, "--", "-C", "linker-flavor=ld.lld",
        "-C", f"linker={linker}", "-C", "relocation-model=pic",
        "-C", f"link-arg=-T{GUEST / 'image.ld'}", "-C", "link-arg=-pie",
        "-C", "link-arg=--no-dynamic-linker", "-C", "link-arg=--no-undefined",
        "-C", "link-arg=--no-gc-sections", "-C", "link-arg=-Bsymbolic",
    ], check=True)
    return target_dir / TARGET / "release/nixe-nvn-guest"


def extract(elf):
    symbols = {
        sym.name: sym["st_value"] for sym in elf.get_section_by_name(".symtab").iter_symbols()
        if sym["st_shndx"] != "SHN_UNDEF"
    }
    version = elf.get_section_by_name(".nvn_version")
    end = symbols["nixe_nvn_version"]
    if end % 4096 or version["sh_addr"] != end or version["sh_size"] != 8:
        raise ValueError("the two version words must follow the page-aligned RX image")

    image = bytearray(end)
    for section in elf.iter_sections():
        if section["sh_type"] in ("SHT_REL", "SHT_RELA") and section.num_relocations():
            raise ValueError("the guest image must run without relocation")
        if section.name in (".text", ".rodata", ".data.rel.ro"):
            start = section["sh_addr"]
            data = section.data()
            if start + len(data) > end:
                raise ValueError(f"{section.name} extends past the RX image")
            image[start:start + len(data)] = data
        elif section["sh_flags"] & 2 and section["sh_size"] and section.name not in (
            ".dynsym", ".dynstr", ".hash", ".dynamic", ".nvn_version",
        ):
            raise ValueError(f"unexpected allocated guest section {section.name}")

    entries = {name: offset for name, offset in symbols.items() if name.startswith("nvn")}
    error_pc = symbols["nixe_nvn_error"]
    code = elf.get_section_by_name(".text")
    if not entries or any(not 0 <= offset < code["sh_size"] for offset in [error_pc, *entries.values()]):
        raise ValueError("NVN entry outside the executable section")
    return image, entries, error_pc


def entry_table(entries, error_pc):
    ampere_handle = entries.pop("nvnDeviceGetTextureHandleAmpere")
    lines = [
        "// Generated by scripts/build-nvn-guest.py.",
        'pub const GUEST_CODE: &[u8] = include_bytes!("../guest/nvn.bin");',
        f"pub const GUEST_ERROR_PC: usize = {error_pc};",
        "pub fn guest_offset(ampere: bool, name: &str) -> Option<usize> {",
        "    if ampere {",
        f'        return (name == "nvnDeviceGetTextureHandle").then_some({ampere_handle});',
        "    }",
        "    Some(match name {",
    ]
    lines.extend(f'        "{name}" => {offset},' for name, offset in sorted(entries.items()))
    lines.extend(["        _ => return None,", "    })", "}"])
    return subprocess.check_output(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"], input="\n".join(lines).encode(),
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in image and offsets")
    args = parser.parse_args()
    with compile_elf().open("rb") as binary:
        image, entries, error_pc = extract(ELFFile(binary))
    for path, data in [
        (GUEST / "nvn.bin", image),
        (ROOT / "crates/nvn/src/guest_image.rs", entry_table(entries, error_pc)),
    ]:
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f"out of date: {path}")
        else:
            path.write_bytes(data)
