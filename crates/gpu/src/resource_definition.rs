//! Decoded resource definitions shared by frontends and the GPU owner.

use crate::{
    BackingView, BufferDescription, BufferId, BufferView, DescriptorTableBinding,
    DescriptorTableDescription, DescriptorTableId, GpuAllocationDescription, GpuAllocationId,
    ImageDescription, ImageId, ImageView, PipelineDescription, PipelineId, QueryPoolDescription,
    QueryPoolId, RenderPassDescription, RenderPassId, ResourceDependency, SamplerDescription,
    SamplerId, ShaderBackendModule, ShaderDescription, ShaderId,
};

/// Complete immutable input used to create one backend resource.
///
/// Logical descriptions remain separate from optional backing views. Shader
/// modules contain verified neutral IR, never guest ISA bytes, backend-language
/// source, or host handles. Host artifacts are generated by the consuming backend.
#[derive(Clone, Debug, PartialEq)]
pub enum ResourceDefinition {
    Allocation {
        id: GpuAllocationId,
        description: GpuAllocationDescription,
    },
    Buffer {
        id: BufferId,
        description: BufferDescription,
        view: Option<BufferView>,
    },
    Image {
        id: ImageId,
        description: ImageDescription,
        view: Option<ImageView>,
    },
    Sampler {
        id: SamplerId,
        description: SamplerDescription,
    },
    Shader {
        id: ShaderId,
        description: ShaderDescription,
        module: ShaderBackendModule,
    },
    Pipeline {
        id: PipelineId,
        description: PipelineDescription,
    },
    DescriptorTable {
        id: DescriptorTableId,
        description: DescriptorTableDescription,
        bindings: Box<[DescriptorTableBinding]>,
    },
    RenderPass {
        id: RenderPassId,
        description: RenderPassDescription,
    },
    QueryPool {
        id: QueryPoolId,
        description: QueryPoolDescription,
    },
}

impl ResourceDefinition {
    #[must_use]
    pub const fn dependency(&self) -> ResourceDependency {
        match self {
            Self::Allocation { id, .. } => ResourceDependency::Allocation(*id),
            Self::Buffer { id, .. } => ResourceDependency::Buffer(*id),
            Self::Image { id, .. } => ResourceDependency::Image(*id),
            Self::Sampler { id, .. } => ResourceDependency::Sampler(*id),
            Self::Shader { id, .. } => ResourceDependency::Shader(*id),
            Self::Pipeline { id, .. } => ResourceDependency::Pipeline(*id),
            Self::DescriptorTable { id, .. } => ResourceDependency::DescriptorTable(*id),
            Self::RenderPass { id, .. } => ResourceDependency::RenderPass(*id),
            Self::QueryPool { id, .. } => ResourceDependency::QueryPool(*id),
        }
    }

    /// Conservative handoff charge, counting shared metadata per reference.
    /// Canonical guest allocations and host objects have separate residency budgets.
    #[must_use]
    pub fn retained_bytes(&self) -> usize {
        std::mem::size_of::<Self>()
            + match self {
                Self::Buffer {
                    view: Some(view), ..
                } => backing_bytes(view.backing()),
                Self::Image {
                    view: Some(view), ..
                } => {
                    std::mem::size_of_val(view.bindings())
                        + view
                            .bindings()
                            .iter()
                            .map(|binding| backing_bytes(binding.backing()))
                            .sum::<usize>()
                }
                Self::Shader { module, .. } => module.retained_bytes(),
                Self::DescriptorTable {
                    description,
                    bindings,
                    ..
                } => {
                    std::mem::size_of_val(description.bindings())
                        + std::mem::size_of_val(bindings.as_ref())
                }
                Self::RenderPass { description, .. } => {
                    std::mem::size_of_val(description.attachments())
                }
                _ => 0,
            }
    }
}

fn backing_bytes(backing: &BackingView) -> usize {
    std::mem::size_of_val(backing.canonical_spans())
}
