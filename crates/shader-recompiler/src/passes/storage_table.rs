use crate::ir::Opcode as O;

pub(super) fn storage_opcode(op: O) -> Option<O> {
    Some(match op {
        O::LoadGlobalS8 => O::LoadStorageS8,
        O::LoadGlobalU8 => O::LoadStorageU8,
        O::LoadGlobalS16 => O::LoadStorageS16,
        O::LoadGlobalU16 => O::LoadStorageU16,
        O::LoadGlobal32 => O::LoadStorage32,
        O::LoadGlobal64 => O::LoadStorage64,
        O::LoadGlobal128 => O::LoadStorage128,
        O::WriteGlobalS8 => O::WriteStorageS8,
        O::WriteGlobalU8 => O::WriteStorageU8,
        O::WriteGlobalS16 => O::WriteStorageS16,
        O::WriteGlobalU16 => O::WriteStorageU16,
        O::WriteGlobal32 => O::WriteStorage32,
        O::WriteGlobal64 => O::WriteStorage64,
        O::WriteGlobal128 => O::WriteStorage128,
        O::GlobalAtomicIAdd32 => O::StorageAtomicIAdd32,
        O::GlobalAtomicSMin32 => O::StorageAtomicSMin32,
        O::GlobalAtomicUMin32 => O::StorageAtomicUMin32,
        O::GlobalAtomicSMax32 => O::StorageAtomicSMax32,
        O::GlobalAtomicUMax32 => O::StorageAtomicUMax32,
        O::GlobalAtomicInc32 => O::StorageAtomicInc32,
        O::GlobalAtomicDec32 => O::StorageAtomicDec32,
        O::GlobalAtomicAnd32 => O::StorageAtomicAnd32,
        O::GlobalAtomicOr32 => O::StorageAtomicOr32,
        O::GlobalAtomicXor32 => O::StorageAtomicXor32,
        O::GlobalAtomicExchange32 => O::StorageAtomicExchange32,
        O::GlobalAtomicIAdd64 => O::StorageAtomicIAdd64,
        O::GlobalAtomicSMin64 => O::StorageAtomicSMin64,
        O::GlobalAtomicUMin64 => O::StorageAtomicUMin64,
        O::GlobalAtomicSMax64 => O::StorageAtomicSMax64,
        O::GlobalAtomicUMax64 => O::StorageAtomicUMax64,
        O::GlobalAtomicAnd64 => O::StorageAtomicAnd64,
        O::GlobalAtomicOr64 => O::StorageAtomicOr64,
        O::GlobalAtomicXor64 => O::StorageAtomicXor64,
        O::GlobalAtomicExchange64 => O::StorageAtomicExchange64,
        O::GlobalAtomicIAdd32x2 => O::StorageAtomicIAdd32x2,
        O::GlobalAtomicSMin32x2 => O::StorageAtomicSMin32x2,
        O::GlobalAtomicUMin32x2 => O::StorageAtomicUMin32x2,
        O::GlobalAtomicSMax32x2 => O::StorageAtomicSMax32x2,
        O::GlobalAtomicUMax32x2 => O::StorageAtomicUMax32x2,
        O::GlobalAtomicAnd32x2 => O::StorageAtomicAnd32x2,
        O::GlobalAtomicOr32x2 => O::StorageAtomicOr32x2,
        O::GlobalAtomicXor32x2 => O::StorageAtomicXor32x2,
        O::GlobalAtomicExchange32x2 => O::StorageAtomicExchange32x2,
        O::GlobalAtomicAddF32 => O::StorageAtomicAddF32,
        O::GlobalAtomicAddF16x2 => O::StorageAtomicAddF16x2,
        O::GlobalAtomicMinF16x2 => O::StorageAtomicMinF16x2,
        O::GlobalAtomicMaxF16x2 => O::StorageAtomicMaxF16x2,
        O::GlobalAtomicAddF32x2 => O::StorageAtomicAddF32x2,
        O::GlobalAtomicMinF32x2 => O::StorageAtomicMinF32x2,
        O::GlobalAtomicMaxF32x2 => O::StorageAtomicMaxF32x2,
        _ => return None,
    })
}
