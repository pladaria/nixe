impl Opcode {
    /// Zero, sparse and shuffle-in-bounds share a reference association slot.
    pub const fn pseudo_slot(self) -> Option<usize> {
        match self {
            Self::GetZeroFromOp | Self::GetSparseFromOp | Self::GetInBoundsFromOp => Some(0),
            Self::GetSignFromOp => Some(1),
            Self::GetCarryFromOp => Some(2),
            Self::GetOverflowFromOp => Some(3),
            _ => None,
        }
    }
}
