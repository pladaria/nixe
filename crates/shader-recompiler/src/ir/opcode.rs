use super::Type;

#[derive(Clone, Copy, Debug)]
pub struct Signature {
    pub result: Type,
    pub arguments: &'static [Type],
    pub side_effects: bool,
}

macro_rules! opcodes {
    ($($name:ident: $result:ident, [$($arg:ident),*], $effect:literal;)*) => {
        #[allow(non_camel_case_types)]
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        #[repr(u16)]
        pub enum Opcode { $($name),* }
        impl Opcode {
            pub const ALL: &'static [Self] = &[$(Self::$name),*];
            pub const fn signature(self) -> &'static Signature {
                &SIGNATURES[self as usize]
            }
            pub const fn name(self) -> &'static str {
                match self { $(Self::$name => stringify!($name)),* }
            }
        }
        static SIGNATURES: &[Signature] = &[$(Signature {
            result: Type::$result, arguments: &[$(Type::$arg),*], side_effects: $effect
        }),*];
    };
}

