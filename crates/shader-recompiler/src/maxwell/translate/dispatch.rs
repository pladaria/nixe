use super::{Opcode, Result, Source, Visitor, unsupported};
impl Visitor<'_> {
    pub(super) fn dispatch(&mut self, opcode: Opcode) -> Result<()> {
        if opcode.encoding().unsupported {
            return Err(unsupported(format!("Unsupported instruction {:?}", opcode)));
        }
        match opcode {
            Opcode::SULD => self.surface_memory(false),
            Opcode::SUST => self.surface_memory(true),
            Opcode::SUATOM => self.surface_atomic(false),
            Opcode::SURED => self.surface_atomic(true),
            Opcode::TEX => self.tex(false),
            Opcode::TEX_b => self.tex(true),
            Opcode::TEXS => self.texs(),
            Opcode::TLD => self.tld(false),
            Opcode::TLD_b => self.tld(true),
            Opcode::TLDS => self.tlds(),
            Opcode::TLD4 => self.tld4(false),
            Opcode::TLD4_b => self.tld4(true),
            Opcode::TLD4S => self.tld4s(),
            Opcode::TXD => self.txd(false),
            Opcode::TXD_b => self.txd(true),
            Opcode::TMML => self.tmml(false),
            Opcode::TMML_b => self.tmml(true),
            Opcode::TXQ => self.txq(false),
            Opcode::TXQ_b => self.txq(true),
            Opcode::LDC => self.ldc(),
            Opcode::LDL => self.local_memory(false),
            Opcode::STL => self.local_memory(true),
            Opcode::LDS => self.shared_memory(false),
            Opcode::STS => self.shared_memory(true),
            Opcode::LDG => self.global_memory(false),
            Opcode::STG => self.global_memory(true),
            Opcode::ATOM => self.global_atomic(false),
            Opcode::RED => self.global_atomic(true),
            Opcode::ATOMS => self.shared_atomic(),
            Opcode::AL2P => self.al2p(),
            Opcode::ALD => self.attribute_memory(false),
            Opcode::AST => self.attribute_memory(true),
            Opcode::IPA => self.ipa(),
            Opcode::ISBERD => self.isberd(),
            Opcode::OUT_reg => self.output(Source::Reg20),
            Opcode::OUT_cbuf => self.output(Source::Cbuf),
            Opcode::OUT_imm => self.output(Source::Imm20),
            Opcode::PIXLD => self.pixld(),
            Opcode::EXIT => self.exit(),
            Opcode::MEMBAR => self.membar(),
            Opcode::BAR => self.bar(),
            Opcode::DEPBAR | Opcode::VOTE_vtg => Ok(()),
            Opcode::VOTE => self.vote(),
            Opcode::SHFL => self.shfl(),
            Opcode::FADD_reg => self.fadd(Source::Reg20, false, false),
            Opcode::FADD_cbuf => self.fadd(Source::Cbuf, false, false),
            Opcode::FADD_imm => self.fadd(Source::Imm20, false, false),
            Opcode::DADD_reg => self.fadd(Source::Reg20, true, false),
            Opcode::DADD_cbuf => self.fadd(Source::Cbuf, true, false),
            Opcode::DADD_imm => self.fadd(Source::Imm20, true, false),
            Opcode::FMUL_reg => self.fmul(Source::Reg20, false, false),
            Opcode::FMUL_cbuf => self.fmul(Source::Cbuf, false, false),
            Opcode::FMUL_imm => self.fmul(Source::Imm20, false, false),
            Opcode::DMUL_reg => self.fmul(Source::Reg20, true, false),
            Opcode::DMUL_cbuf => self.fmul(Source::Cbuf, true, false),
            Opcode::DMUL_imm => self.fmul(Source::Imm20, true, false),
            Opcode::FMNMX_reg => self.fmnmx(Source::Reg20, false),
            Opcode::FMNMX_cbuf => self.fmnmx(Source::Cbuf, false),
            Opcode::FMNMX_imm => self.fmnmx(Source::Imm20, false),
            Opcode::DMNMX_reg => self.fmnmx(Source::Reg20, true),
            Opcode::DMNMX_cbuf => self.fmnmx(Source::Cbuf, true),
            Opcode::DMNMX_imm => self.fmnmx(Source::Imm20, true),
            Opcode::FSET_reg => self.fset(Source::Reg20, false, false),
            Opcode::FSET_cbuf => self.fset(Source::Cbuf, false, false),
            Opcode::FSET_imm => self.fset(Source::Imm20, false, false),
            Opcode::DSET_reg => self.fset(Source::Reg20, true, false),
            Opcode::DSET_cbuf => self.fset(Source::Cbuf, true, false),
            Opcode::DSET_imm => self.fset(Source::Imm20, true, false),
            Opcode::FSETP_reg => self.fset(Source::Reg20, false, true),
            Opcode::FSETP_cbuf => self.fset(Source::Cbuf, false, true),
            Opcode::FSETP_imm => self.fset(Source::Imm20, false, true),
            Opcode::DSETP_reg => self.fset(Source::Reg20, true, true),
            Opcode::DSETP_cbuf => self.fset(Source::Cbuf, true, true),
            Opcode::DSETP_imm => self.fset(Source::Imm20, true, true),
            Opcode::FADD32I => self.fadd(Source::Imm32, false, true),
            Opcode::FMUL32I => self.fmul(Source::Imm32, false, true),
            Opcode::FFMA_reg => self.ffma(Source::Reg20, Source::Reg39, false, false),
            Opcode::FFMA_rc => self.ffma(Source::Reg39, Source::Cbuf, false, false),
            Opcode::FFMA_cr => self.ffma(Source::Cbuf, Source::Reg39, false, false),
            Opcode::FFMA_imm => self.ffma(Source::Imm20, Source::Reg39, false, false),
            Opcode::DFMA_reg => self.ffma(Source::Reg20, Source::Reg39, true, false),
            Opcode::DFMA_rc => self.ffma(Source::Reg39, Source::Cbuf, true, false),
            Opcode::DFMA_cr => self.ffma(Source::Cbuf, Source::Reg39, true, false),
            Opcode::DFMA_imm => self.ffma(Source::Imm20, Source::Reg39, true, false),
            Opcode::FFMA32I => self.ffma(Source::Imm32, Source::Reg0, false, true),
            Opcode::FCMP_reg => self.fcmp(Source::Reg20, Source::Reg39),
            Opcode::FCMP_rc => self.fcmp(Source::Reg39, Source::Cbuf),
            Opcode::FCMP_cr => self.fcmp(Source::Cbuf, Source::Reg39),
            Opcode::FCMP_imm => self.fcmp(Source::Imm20, Source::Reg39),
            Opcode::F2F_reg => self.f2f(Source::Reg20),
            Opcode::F2F_cbuf => self.f2f(Source::Cbuf),
            Opcode::F2F_imm => self.f2f(Source::Imm20),
            Opcode::F2I_reg => self.f2i(Source::Reg20),
            Opcode::F2I_cbuf => self.f2i(Source::Cbuf),
            Opcode::I2F_reg => self.i2f(Source::Reg20),
            Opcode::I2F_cbuf => self.i2f(Source::Cbuf),
            Opcode::I2F_imm => self.i2f(Source::Imm20),
            Opcode::RRO_reg => self.rro(Source::Reg20),
            Opcode::RRO_cbuf => self.rro(Source::Cbuf),
            Opcode::MUFU => self.mufu(),
            Opcode::FSWZADD => self.fswzadd(),
            Opcode::HADD2_reg
            | Opcode::HADD2_cbuf
            | Opcode::HADD2_imm
            | Opcode::HADD2_32I
            | Opcode::HMUL2_reg
            | Opcode::HMUL2_cbuf
            | Opcode::HMUL2_imm
            | Opcode::HMUL2_32I => self.half_arithmetic(opcode),
            Opcode::HFMA2_reg
            | Opcode::HFMA2_rc
            | Opcode::HFMA2_cr
            | Opcode::HFMA2_imm
            | Opcode::HFMA2_32I => self.hfma(opcode),
            Opcode::HSET2_reg => self.hset(Source::Reg20, false),
            Opcode::HSET2_cbuf => self.hset(Source::Cbuf, false),
            Opcode::HSET2_imm => self.hset(Source::Imm20, false),
            Opcode::HSETP2_reg => self.hset(Source::Reg20, true),
            Opcode::HSETP2_cbuf => self.hset(Source::Cbuf, true),
            Opcode::HSETP2_imm => self.hset(Source::Imm20, true),
            Opcode::LEA_hi_reg => self.lea(Source::Reg20, true),
            Opcode::LEA_hi_cbuf => self.lea(Source::Cbuf, true),
            Opcode::LEA_lo_reg => self.lea(Source::Reg20, false),
            Opcode::LEA_lo_cbuf => self.lea(Source::Cbuf, false),
            Opcode::LEA_lo_imm => self.lea(Source::Imm20, false),
            Opcode::BRX | Opcode::JMX => {
                if self.bit::<5>() {
                    return Err(unsupported("Indirect branch constant buffer mode"));
                }
                if self.bit::<6>() {
                    return Err(unsupported("Indirect branch LMT"));
                }
                Ok(())
            }
            Opcode::MOV_reg => self.mov(Source::Reg20, false),
            Opcode::MOV_cbuf => self.mov(Source::Cbuf, false),
            Opcode::MOV_imm => self.mov(Source::Imm20, false),
            Opcode::SEL_reg => self.sel(Source::Reg20),
            Opcode::SEL_cbuf => self.sel(Source::Cbuf),
            Opcode::SEL_imm => self.sel(Source::Imm20),
            Opcode::IADD_reg => self.iadd(Source::Reg20, false),
            Opcode::IADD_cbuf => self.iadd(Source::Cbuf, false),
            Opcode::IADD_imm => self.iadd(Source::Imm20, false),
            Opcode::IADD3_reg => self.iadd3(Source::Reg20, true),
            Opcode::IADD3_cbuf => self.iadd3(Source::Cbuf, false),
            Opcode::IADD3_imm => self.iadd3(Source::Imm20, false),
            Opcode::ISCADD_reg => self.iscadd(Source::Reg20, false),
            Opcode::ISCADD_cbuf => self.iscadd(Source::Cbuf, false),
            Opcode::ISCADD_imm => self.iscadd(Source::Imm20, false),
            Opcode::IMNMX_reg => self.imnmx(Source::Reg20),
            Opcode::IMNMX_cbuf => self.imnmx(Source::Cbuf),
            Opcode::IMNMX_imm => self.imnmx(Source::Imm20),
            Opcode::SHL_reg => self.shift(Source::Reg20, false),
            Opcode::SHL_cbuf => self.shift(Source::Cbuf, false),
            Opcode::SHL_imm => self.shift(Source::Imm20, false),
            Opcode::SHR_reg => self.shift(Source::Reg20, true),
            Opcode::SHR_cbuf => self.shift(Source::Cbuf, true),
            Opcode::SHR_imm => self.shift(Source::Imm20, true),
            Opcode::POPC_reg => self.popc(Source::Reg20),
            Opcode::POPC_cbuf => self.popc(Source::Cbuf),
            Opcode::POPC_imm => self.popc(Source::Imm20),
            Opcode::FLO_reg => self.flo(Source::Reg20),
            Opcode::FLO_cbuf => self.flo(Source::Cbuf),
            Opcode::FLO_imm => self.flo(Source::Imm20),
            Opcode::BFE_reg => self.bfe(Source::Reg20),
            Opcode::BFE_cbuf => self.bfe(Source::Cbuf),
            Opcode::BFE_imm => self.bfe(Source::Imm20),
            Opcode::I2I_reg => self.i2i(Source::Reg20),
            Opcode::I2I_cbuf => self.i2i(Source::Cbuf),
            Opcode::I2I_imm => self.i2i(Source::Imm20),
            Opcode::ISET_reg => self.iset(Source::Reg20, false),
            Opcode::ISET_cbuf => self.iset(Source::Cbuf, false),
            Opcode::ISET_imm => self.iset(Source::Imm20, false),
            Opcode::ISETP_reg => self.iset(Source::Reg20, true),
            Opcode::ISETP_cbuf => self.iset(Source::Cbuf, true),
            Opcode::ISETP_imm => self.iset(Source::Imm20, true),
            Opcode::R2P_reg => self.r2p(Source::Reg20),
            Opcode::R2P_cbuf => self.r2p(Source::Cbuf),
            Opcode::R2P_imm => self.r2p(Source::Imm20),
            Opcode::LOP_reg => self.lop(Source::Reg20, false),
            Opcode::LOP_cbuf => self.lop(Source::Cbuf, false),
            Opcode::LOP_imm => self.lop(Source::Imm20, false),
            Opcode::LOP3_reg => self.lop3(Source::Reg20, true),
            Opcode::LOP3_cbuf => self.lop3(Source::Cbuf, false),
            Opcode::LOP3_imm => self.lop3(Source::Imm20, false),
            Opcode::MOV32I => self.mov(Source::Imm32, true),
            Opcode::IADD32I => self.iadd(Source::Imm32, true),
            Opcode::ISCADD32I => self.iscadd(Source::Imm32, true),
            Opcode::LOP32I => self.lop(Source::Imm32, true),
            Opcode::BFI_reg => self.bfi(Source::Reg20, Source::Reg39),
            Opcode::BFI_rc => self.bfi(Source::Reg39, Source::Cbuf),
            Opcode::BFI_cr => self.bfi(Source::Cbuf, Source::Reg39),
            Opcode::BFI_imm => self.bfi(Source::Imm20, Source::Reg39),
            Opcode::ICMP_reg => self.icmp(Source::Reg20, Source::Reg39),
            Opcode::ICMP_rc => self.icmp(Source::Reg39, Source::Cbuf),
            Opcode::ICMP_cr => self.icmp(Source::Cbuf, Source::Reg39),
            Opcode::ICMP_imm => self.icmp(Source::Imm20, Source::Reg39),
            Opcode::SHF_l_reg => self.shf(Source::Reg20, false),
            Opcode::SHF_l_imm => self.shf(Source::Imm20, false),
            Opcode::SHF_r_reg => self.shf(Source::Reg20, true),
            Opcode::SHF_r_imm => self.shf(Source::Imm20, true),
            Opcode::XMAD_reg | Opcode::XMAD_rc | Opcode::XMAD_cr | Opcode::XMAD_imm => {
                self.xmad(opcode)
            }
            Opcode::CSET => self.cset(false),
            Opcode::CSETP => self.cset(true),
            Opcode::PSET => self.pset(false),
            Opcode::PSETP => self.pset(true),
            Opcode::P2R_imm => self.p2r(),
            Opcode::S2R => self.s2r(),
            Opcode::VMAD | Opcode::VMNMX | Opcode::VSETP => self.video(opcode),
            Opcode::CAL
            | Opcode::KIL
            | Opcode::NOP
            | Opcode::PBK
            | Opcode::PCNT
            | Opcode::SSY
            | Opcode::RAM
            | Opcode::SAM => Ok(()),
            _ => Err(unsupported(format!(
                "Instruction {:?} translation is not implemented",
                opcode
            ))),
        }
    }
}
